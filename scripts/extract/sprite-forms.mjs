/**
 * scripts/extract/sprite-forms.mjs — shared form-sprite resolver.
 *
 * Zero dependencies (node:fs, node:path only — the callers pass in all the
 * text; this module never touches the repo). Imported by BOTH extractors:
 *
 *   - scripts/extract/sprites.mjs  — composites + writes the own-art files
 *     through the exact same 64×64 / frame-0 / JASC 8→5→8 pipeline as the
 *     base species; it ALSO resolves every branch's base species
 *     directory through this module's BASE_CANDIDATES (the single source
 *     of the candidate order — it keeps no local mirror) and excludes
 *     NON_SPECIES_DIRS from the manifest's baseDirs;
 *   - scripts/extract/pokedex.mjs  — sets `form.sprite = <formEntryId>` on
 *     every structured form that owns its art (a bare string — the file
 *     name without `.png`) and cites the form's resolved EX source files.
 *     It also gates that every roster-referenced own form has its shipped
 *     PNG on disk (the cross-extractor drift guard).
 *
 * File convention (site/assets/pokemon/): a structured form with its own
 * art ships as the FLAT `<formEntryId>.png` — e.g. `charizard_mega_x.png` —
 * never a nested path. Base species keep their existing `<id>.png` /
 * `<id>-ex.png` names.
 *
 * The mechanical rule (no per-form list, no curated exceptions except the
 * documented ternary-macro case below):
 *
 *   1. Parse the EX INCBIN tables in `src/data/graphics/pokemon.h`:
 *      `gMonFrontPic_X[]` / `gMonPalette_X[]` → the `.4bpp`/`.gbapal`
 *      source each symbol points at.
 *   2. Parse the EX species tables (`src/data/pokemon/species_info/gen_1..9.h`
 *      + `species_info.h`) RAW — with `#define`s intact — expanding
 *      function-like and object-like macros to a fixed point, including `##`
 *      token pasting (the OGERPON / XERNEAS / SILVALLY / MINIOR / GENESECT
 *      family initializers are one-line macro calls, not brace bodies).
 *      Each entry's final `.frontPic` / `.palette` symbols are looked up in
 *      the INCBIN tables.
 *   3. An entry whose id names a top-level species art directory is a BASE
 *      entry. Every other entry is a FORM: its resolved (front, palette)
 *      pair is compared against its base directory's resolved pair (the
 *      shared BASE_CANDIDATES order — front.png/normal.pal first, then
 *      anim_front.png/normal.pal, then the vanilla-only castform/unown
 *      layouts). Equal →
 *      `base-identical` (no dedicated file: the base sprite already looks
 *      right); different → `own` (a dedicated `<formEntryId>.png`: the
 *      form's own front file — often the base bitmap with a form-specific
 *      palette directory — composited with the form's palette).
 *   4. Deliberate fallback: a form id that is NOT a species entry at all
 *      (the rogue-only custom forms, e.g. shiny_groudon — no INCBIN symbol,
 *      no species table row) gets NO file and NO `form.sprite`; the site
 *      falls back to the base sprite. That is the intended behaviour, not
 *      an error.
 *   5. Roster filter (`formRosterDomain`): an `own` entry ships a file
 *      only when its id is referenced by some record's form roster (the
 *      profile Species list, else the family form table — the same rule
 *      the pokedex extractor uses for the records' `forms` fields). The
 *      full Alcremie/Minior/Pikachu-cap species families the game imports
 *      but never displays are unreferenced dead data — no file.
 *
 * Documented special case — `TERNARY_MACRO_FORMS`:
 *   `silvally_fairy` is resolved by the rule to `own` (base front + the
 *   fairy palette), like its sixteen sibling forms — but it is excluded
 *   from the dedicated-file set and uses the base art. The Silvally family
 *   is generated by a ternary-laden macro (the family's pokedex text is a
 *   type-conditional ternary, and the fairy entry's initializer is the
 *   macro call that swallows the next entry in a naive body slice), so the
 *   dedicated-art decision for that one entry is pinned here by name
 *   rather than re-derived by a slicer. The manifest gate below verifies
 *   the pin is still accurate (the entry exists, is a form, and would
 *   mechanically be `own`) — if the game ever changes, the gate fails
 *   loudly instead of shipping a stale exception.
 *
 * Gate semantics: every failure is a hard `Error` with a complete message —
 * the extractors treat an unresolvable entry, a missing EX source file for
 * an `own` pair, a name/art-directory collision, or a stale ternary pin as
 * a run-time error (non-zero exit).
 */

// The one form whose dedicated-art decision is pinned by name (see the
// "Documented special case" note above). Every id here MUST resolve to an
// entry that is mechanically `own`; the manifest gate enforces that.
export const TERNARY_MACRO_FORMS = new Set(['silvally_fairy']);

// The `gSpeciesInfo[]` array's two non-Pokémon slots: the "????" unknown
// placeholder and the egg slot (both live in species_info.h itself, around
// the gen_1..9.h includes). They are not dex species and never forms —
// they are excluded from the manifest domain. The pokedex extractor's
// entry-set consistency gate subtracts the same set.
export const NON_SPECIES_ENTRIES = new Set(['none', 'egg']);

// Top-level graphics/pokemon/ directories that are NOT species art
// directories (the shared icon palettes + the "???" placeholder art).
// The manifest's baseDirs contract is "top-level SPECIES art
// directories", so both extractors exclude these when they build it
// (see the call sites); sprites.mjs additionally skips them in its
// per-species union loop.
export const NON_SPECIES_DIRS = new Set(['icon_palettes', 'question_mark']);

// The base-candidate order — the single source of truth for "which
// (front, palette) layout a species art directory uses": first candidate
// present in BOTH the base dir and the EX tree wins. OWNED here and
// consumed by both extractors — scripts/extract/sprites.mjs resolves
// every branch's species directory through this SAME list (imported, no
// local mirror), so the base pipeline and the form pass below can never
// resolve a directory differently. `name` is sprites.mjs's per-candidate
// report label (this module ignores it).
export const BASE_CANDIDATES = [
  { png: 'front.png', pal: 'normal.pal', name: 'front.png' },
  { png: 'anim_front.png', pal: 'normal.pal', name: 'anim_front.png (frame 0)' },
  { png: 'front_normal_form.png', pal: 'normal_normal_form.pal', name: 'front_normal_form.png (castform)' },
  { png: 'a/front.png', pal: 'normal.pal', name: 'a/front.png (unown)' },
];

// Flat output file name for a form entry that owns its art.
export function formSpriteFile(entryId) {
  return `${entryId}.png`;
}

/**
 * INCBIN path → repo source path (`.4bpp.lz` → `.png`, `.gbapal.lz` → `.pal`).
 */
export function incbinSourcePath(incbinPath) {
  if (incbinPath.endsWith('.4bpp.lz')) return incbinPath.slice(0, -'.4bpp.lz'.length) + '.png';
  if (incbinPath.endsWith('.gbapal.lz')) return incbinPath.slice(0, -'.gbapal.lz'.length) + '.pal';
  throw new Error(`unknown INCBIN suffix in ${incbinPath}`);
}

/**
 * Parse the EX `src/data/graphics/pokemon.h` INCBIN tables.
 * Returns { fronts: Map<fullSymbol, sourcePath>, palettes: Map<fullSymbol, sourcePath> }
 * (keys are the full `gMonFrontPic_X` / `gMonPalette_X` symbols; source
 * paths are `graphics/pokemon/…` repo-relative). Duplicate symbols fail —
 * the game would not build with two definitions of one symbol.
 */
export function parseSpriteTables(pokemonH) {
  const fronts = new Map();
  const palettes = new Map();
  const put = (map, sym, incbin) => {
    if (map.has(sym)) throw new Error(`duplicate INCBIN symbol ${sym} in pokemon.h`);
    map.set(sym, incbinSourcePath(incbin));
  };
  for (const m of pokemonH.matchAll(/const u32 gMonFrontPic_([A-Za-z0-9_]+)\[\]\s*=\s*INCBIN_U32\("graphics\/pokemon\/([a-z0-9_\/]+\.4bpp\.lz)"\)/g)) {
    put(fronts, `gMonFrontPic_${m[1]}`, `graphics/pokemon/${m[2]}`);
  }
  for (const m of pokemonH.matchAll(/const u32 gMonPalette_([A-Za-z0-9_]+)\[\]\s*=\s*INCBIN_U32\("graphics\/pokemon\/([a-z0-9_\/]+\.gbapal\.lz)"\)/g)) {
    put(palettes, `gMonPalette_${m[1]}`, `graphics/pokemon/${m[2]}`);
  }
  if (fronts.size < 1000) throw new Error(`parsed only ${fronts.size} gMonFrontPic_* INCBIN entries — pokemon.h shape changed?`);
  if (palettes.size < 1000) throw new Error(`parsed only ${palettes.size} gMonPalette_* INCBIN entries — pokemon.h shape changed?`);
  return { fronts, palettes };
}

