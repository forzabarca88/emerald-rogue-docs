/**
 * Collect #defines from raw header text (line continuations honoured).
 * Function-like macros keep their parameter list; object-like ones have an
 * empty one. Later definitions win (C semantics).
 */
export function collectMacros(texts) {
  const macros = new Map();
  for (const txt of texts) {
    const lines = txt.split('\n');
    let i = 0;
    while (i < lines.length) {
      const m = /^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s*(\(([^)]*)\))?\s*(.*)$/.exec(lines[i]);
      if (m) {
        const params = (m[3] || '').split(',').map((s) => s.trim()).filter(Boolean);
        let rest = (m[4] || '').trim();
        let body;
        if (rest.endsWith('\\')) {
          const parts = [rest.replace(/\\$/, '')];
          let j = i + 1;
          while (j < lines.length) {
            const l = lines[j];
            parts.push(l.replace(/\\$/, '').trim());
            if (!l.trimEnd().endsWith('\\')) break;
            j++;
          }
          body = parts.join(' ').trim();
          i = j;
        } else {
          body = rest;
        }
        macros.set(m[1], { params, body });
      }
      i++;
    }
  }
  return macros;
}

/**
 * Blank out line comments (//) and block comments (slash-star … star-slash),
 * string-literal aware, in one pass. The
 * species headers carry a commented-out `[SPECIES_NONE]` template block —
 * a raw slice would see it as a duplicate entry. Offsets are preserved
 * (comments become spaces).
 */
export function stripComments(text) {
  let out = '';
  let inStr = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const n = text[i + 1];
    if (inStr) {
      out += c;
      if (c === '\\') { out += n ?? ''; i++; }
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === '/' && n === '/') {
      while (i < text.length && text[i] !== '\n') { out += ' '; i++; }
      continue;
    }
    if (c === '/' && n === '*') {
      out += '  '; i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) { out += text[i] === '\n' ? '\n' : ' '; i++; }
      if (i < text.length) { out += '  '; i += 2; }
      continue;
    }
    out += c;
  }
  return out;
}

/** C `##` token pasting, to a fixed point. */
function paste(s) {
  let prev;
  do {
    prev = s;
    s = s.replace(/([A-Za-z0-9_]+)\s*##\s*([A-Za-z0-9_]+)/g, '$1$2');
  } while (s !== prev);
  return s;
}

/** Split a macro-argument list on top-level commas (string/brace aware). */
function splitArgs(s) {
  const args = [];
  let d = 0, a = 0, inStr = false;
  for (let p = 0; p < s.length; p++) {
    const c = s[p];
    if (inStr) {
      if (c === '\\') p++;
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') inStr = true;
    else if (c === '(' || c === '{') d++;
    else if (c === ')' || c === '}') d--;
    else if (c === ',' && d === 0) { args.push(s.slice(a, p).trim()); a = p + 1; }
  }
  args.push(s.slice(a).trim());
  return args;
}

/** Find the leftmost expandable `name(…)` call at/after `from`. */
function findCall(text, name, from) {
  let idx = from;
  while ((idx = text.indexOf(name, idx)) !== -1) {
    if (idx > 0 && /[A-Za-z0-9_]/.test(text[idx - 1])) { idx++; continue; }
    let p = idx + name.length;
    while (p < text.length && /\s/.test(text[p])) p++;
    if (text[p] !== '(') { idx = p; continue; }
    let start = p + 1, depth = 1, end = start, inStr = false;
    for (let q = start; q < text.length; q++) {
      const c = text[q];
      if (inStr) {
        if (c === '\\') q++;
        else if (c === '"') inStr = false;
        continue;
      }
      if (c === '"') inStr = true;
      else if (c === '(') depth++;
      else if (c === ')') { depth--; if (depth === 0) { end = q; break; } }
    }
    if (end === start) return null;
    return { idx, end, argstr: text.slice(start, end) };
  }
  return null;
}

/**
 * Expand a macro-initializer body to a fixed point: one function-like call
 * (longest macro name first) per round, then object-like whole-token
 * substitution, then `##` pasting. `EVOLUTION(…)` and the pokedex-text
 * string macros stay verbatim when they are not defined in the passed
 * header set — the fields this module reads (frontPic/palette) never
 * depend on them.
 */
export function expandBody(text, macros) {
  let out = text;
  for (let round = 0; round < 64; round++) {
    let next = out;
    let changed = false;
    const names = [...macros.keys()].filter((n) => macros.get(n).params.length > 0).sort((a, b) => b.length - a.length);
    for (const name of names) {
      const def = macros.get(name);
      let from = 0;
      let call;
      while ((call = findCall(next, name, from))) {
        const args = splitArgs(call.argstr);
        if (args.length !== def.params.length && !(def.params.length === 1 && def.params[0] === '...')) { from = call.idx + name.length; continue; }
        let b = def.body;
        if (!(def.params.length === 1 && def.params[0] === '...')) {
          const sorted = [...def.params].sort((x, y) => y.length - x.length);
          for (const pn of sorted) {
            const ai = def.params.indexOf(pn);
            b = b.replace(new RegExp(`\\b${pn.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'g'), () => args[ai]);
          }
        } else {
          b = b.replaceAll('__VA_ARGS__', call.argstr);
        }
        b = paste(b);
        next = next.slice(0, call.idx) + b + next.slice(call.end + 1);
        changed = true;
        break;
      }
      if (changed) break;
    }
    for (const [name, def] of macros) {
      if (def.params.length > 0) continue;
      const re = new RegExp(`\\b${name}\\b(?!\\s*\\()`, 'g');
      if (re.test(next)) { next = next.replace(re, () => def.body); changed = true; }
    }
    next = paste(next);
    if (!changed) break;
    out = next;
  }
  return out;
}

/** Read one `.field = value` from expanded initializer text. */
function field(body, name) {
  const m = new RegExp(`\\.${name}\\s*=\\s*([^,}\\n]+)`).exec(body);
  return m ? m[1].trim() : null;
}

/**
 * Slice `[SPECIES_X] = <initializer>` pairs out of RAW species-table text.
 * Brace initializers keep their inside; macro-call initializers keep the
 * full `NAME(args)` (the name is what expansion needs).
 */
export function sliceEntries(text) {
  const out = [];
  const re = /\[SPECIES_([A-Z0-9_]+)\]\s*=\s*/g;
  let m;
  while ((m = re.exec(text))) {
    const id = m[1];
    let i = re.lastIndex;
    while (i < text.length && /\s/.test(text[i])) i++;
    let body;
    if (text[i] === '{') {
      let depth = 0, close = -1, inStr = false;
      for (let p = i; p < text.length; p++) {
        const c = text[p];
        if (inStr) {
          if (c === '\\') p++;
          else if (c === '"') inStr = false;
        } else if (c === '"') inStr = true;
        else if (c === '{') depth++;
        else if (c === '}') { depth--; if (depth === 0) { close = p; break; } }
      }
      if (close < 0) throw new Error(`unbalanced brace for [SPECIES_${id}]`);
      body = text.slice(i + 1, close);
    } else if (/[A-Za-z_]/.test(text[i] ?? '')) {
      let j = i;
      while (j < text.length && /[A-Za-z0-9_]/.test(text[j])) j++;
      let k = j;
      while (k < text.length && /\s/.test(text[k])) k++;
      if (text[k] !== '(') throw new Error(`object-like initializer (unexpected) for [SPECIES_${id}]`);
      let depth = 0, end = -1, inStr = false;
      for (let p = k; p < text.length; p++) {
        const c = text[p];
        if (inStr) {
          if (c === '\\') p++;
          else if (c === '"') inStr = false;
          continue;
        }
        if (c === '"') inStr = true;
        else if (c === '(') depth++;
        else if (c === ')') { depth--; if (depth === 0) { end = p; break; } }
      }
      if (end < 0) throw new Error(`unbalanced parens for [SPECIES_${id}]`);
      body = text.slice(i, end + 1);
    } else {
      throw new Error(`unexpected initializer for [SPECIES_${id}]`);
    }
    out.push({ id, body });
  }
  return out;
}

