/**
 * Build the form-sprite manifest from the EX ground truth.
 *
 * @param {object} opts
 * @param {string} opts.pokemonH            RAW text of origin/expansion:src/data/graphics/pokemon.h
 * @param {string[]} opts.speciesTableTexts RAW text of the EX species-table headers
 *                                          (species_info/gen_1..9.h + species_info.h, in that order)
 * @param {Set<string>} opts.baseDirs       top-level SPECIES art directories (lowercase id) —
 *                                          the union of the vanilla working tree and the EX
 *                                          tree, with the shared NON_SPECIES_DIRS excluded
 * @param {Set<string>} opts.exTreeFiles    every file under origin/expansion graphics/pokemon/
 *                                          (paths relative to graphics/pokemon/)
 * @param {string} [opts.label]             prefix for error messages
 *
 * @returns the manifest:
 *   - entries:     Map<id, { id, frontPath, palPath, baseDir }> (id lowercased;
 *                  frontPath/palPath are `graphics/pokemon/…` repo-relative)
 *   - baseEntries: Set<id> — ids that name their own top-level art directory
 *   - forms:       Map<id, { cls, frontPath, palPath, basePair }> for every
 *                  non-base entry (cls: 'own' | 'base-identical' | 'ternary-macro')
 *   - counts:      { base, own, baseIdentical, ternary }
 *   - classify(id): { own, reason, frontPath?, palPath? } — the single lookup
 *                  both extractors use (reason: 'own' | 'base-identical' |
 *                  'ternary-macro' | 'no-entry')
 */
export function formSpriteManifest({ pokemonH, speciesTableTexts, baseDirs, exTreeFiles, label = 'form-sprites' }) {
  const die = (msg) => { throw new Error(`${label}: ${msg}`); };
  if (!(baseDirs instanceof Set)) die('baseDirs must be a Set of top-level art-directory ids');
  if (!(exTreeFiles instanceof Set)) die('exTreeFiles must be a Set of paths relative to graphics/pokemon/');

  const { fronts, palettes } = parseSpriteTables(pokemonH);

  const cleanTexts = speciesTableTexts.map((t) => stripComments(t));
  const macros = collectMacros(cleanTexts);
  const seen = new Set();
  const entries = new Map();
  for (const txt of cleanTexts) {
    for (const e of sliceEntries(txt)) {
      const id = e.id.toLowerCase();
      if (NON_SPECIES_ENTRIES.has(id)) continue; // the array's placeholder/egg slots
      if (seen.has(id)) die(`duplicate species entry [SPECIES_${e.id}]`);
      seen.add(id);
      const expanded = expandBody(e.body, macros);
      const frontSym = field(expanded, 'frontPic');
      const palSym = field(expanded, 'palette');
      if (!frontSym || !/^gMonFrontPic_[A-Za-z0-9_]+$/.test(frontSym)) {
        die(`entry [SPECIES_${e.id}]: .frontPic did not resolve to a bare gMonFrontPic_* symbol (got: ${frontSym ?? 'nothing'})`);
      }
      if (!palSym || !/^gMonPalette_[A-Za-z0-9_]+$/.test(palSym)) {
        die(`entry [SPECIES_${e.id}]: .palette did not resolve to a bare gMonPalette_* symbol (got: ${palSym ?? 'nothing'})`);
      }
      const frontPath = fronts.get(frontSym);
      const palPath = palettes.get(palSym);
      if (!frontPath) die(`entry [SPECIES_${e.id}]: ${frontSym} has no INCBIN front (not in pokemon.h)`);
      if (!palPath) die(`entry [SPECIES_${e.id}]: ${palSym} has no INCBIN palette (not in pokemon.h)`);
      entries.set(id, { id, frontPath, palPath, baseDir: frontPath.split('/')[2] });
    }
  }
  if (entries.size < 1500) die(`only ${entries.size} species entries parsed (expected ~1503) — species-table shape changed?`);

  // base-directory candidate resolution (the shared BASE_CANDIDATES order —
  // the same list sprites.mjs resolves every branch's species dir through)
  const basePair = (dir) => {
    for (const { png, pal } of BASE_CANDIDATES) {
      if (exTreeFiles.has(`${dir}/${png}`) && exTreeFiles.has(`${dir}/${pal}`)) return [`${dir}/${png}`, `${dir}/${pal}`];
    }
    return null;
  };

  const baseEntries = new Set();
  const forms = new Map();
  const counts = { base: 0, own: 0, baseIdentical: 0, ternary: 0 };
  for (const [id, e] of entries) {
    if (baseDirs.has(id)) {
      if (e.baseDir !== id) die(`collision: entry ${id} names art directory ${e.baseDir} (a different top-level species directory)`);
      baseEntries.add(id);
      counts.base++;
      continue;
    }
    if (TERNARY_MACRO_FORMS.has(id)) {
      // gate: the pin must still be accurate — a form entry that would
      // mechanically be `own` (its pair differs from the base dir's pair)
      const bp = basePair(e.baseDir);
      if (!bp) die(`ternary pin ${id}: base dir ${e.baseDir} has no resolvable candidate pair`);
      if (e.frontPath === `graphics/pokemon/${bp[0]}` && e.palPath === `graphics/pokemon/${bp[1]}`) {
        die(`ternary pin ${id} is stale: the entry is base-identical now, drop it from TERNARY_MACRO_FORMS`);
      }
      forms.set(id, { cls: 'ternary-macro', frontPath: e.frontPath, palPath: e.palPath, basePair: bp });
      counts.ternary++;
      continue;
    }
    const bp = basePair(e.baseDir);
    if (!bp) die(`form ${id}: base dir ${e.baseDir} has no resolvable candidate pair (front.png/anim_front.png/… + palette) in the EX tree`);
    const [bFront, bPal] = ['graphics/pokemon/' + bp[0], 'graphics/pokemon/' + bp[1]];
    if (e.frontPath === bFront && e.palPath === bPal) {
      forms.set(id, { cls: 'base-identical', frontPath: e.frontPath, palPath: e.palPath, basePair: bp });
      counts.baseIdentical++;
    } else {
      // gate: the own pair's sources must exist in the EX tree
      for (const p of [e.frontPath, e.palPath]) {
        if (!exTreeFiles.has(p.slice('graphics/pokemon/'.length))) die(`form ${id}: source ${p} not in the EX tree`);
      }
      forms.set(id, { cls: 'own', frontPath: e.frontPath, palPath: e.palPath, basePair: bp });
      counts.own++;
    }
  }

  // gate: every pinned ternary id must actually be an entry (a stale pin
  // pointing at a removed entry would otherwise silently do nothing)
  for (const id of TERNARY_MACRO_FORMS) {
    if (!entries.has(id)) die(`TERNARY_MACRO_FORMS pins ${id}, but it is not a species entry anymore — update the set`);
  }

  return {
    entries,
    baseEntries,
    forms,
    counts,
    classify(id) {
      const f = forms.get(id);
      if (f) {
        return f.cls === 'own'
          ? { own: true, reason: 'own', frontPath: f.frontPath, palPath: f.palPath }
          : { own: false, reason: f.cls, frontPath: f.frontPath, palPath: f.palPath };
      }
      return { own: false, reason: 'no-entry' };
    },
  };
}

// ---------------------------------------------------------------------------
// Form rosters — which form ids a record's `forms` list carries
// ---------------------------------------------------------------------------

/**
 * The per-record form rosters — the rule the Pokedex data uses to decide
 * which forms each record lists:
 *
 *   roster(R) = profile(R).species[1..]   when R's expansion profile lists
 *                                         more than the base species (the
 *                                         profile's Species list is the
 *                                         authoritative roster)
 *                else the ids of R's family form table, minus R
 *   (when R has no profile of its own, the profile of R's family-table base
 *    — the first record member of that table — is consulted first, exactly
 *    as the pokedex extractor does)
 *
 * `referenced` — the union of every roster — is the set of form ids the
 * data will ever reference. The sprite extractor ships art for exactly
 * `referenced ∩ own`: species-table entries that no roster reaches (the
 * full Alcremie/Minior/Pikachu-cap families the game imports but never
 * displays) are dead game data and deliberately get no file.
 *
 * @param {object} opts
 * @param {string} opts.pokedexH            RAW text of
 *                                          origin/expansion:include/constants/pokedex.h
 *                                          (the national enum block itself
 *                                          carries no #if guards)
 * @param {string[]} opts.speciesTableTexts RAW text of the EX species-table
 *                                          headers (gen_1..9.h +
 *                                          species_info.h) — macro expansion
 *                                          recovers `.formSpeciesIdTable` /
 *                                          `.natDexNum` from the MISC_INFO
 *                                          macros
 * @param {string[]} opts.formTableTexts    RAW text of the two form-table
 *                                          headers (form_species_tables.h,
 *                                          form_change_tables.h)
 * @param {Map<string, string[]>} opts.profiles  parsed expansion-profile
 *                                          Species lists (id → lowercased
 *                                          species ids, in file order), for
 *                                          every id whose profile file exists
 * @param {string} [opts.label]
 *
 * @returns {
 *   records: string[],              // the 1025 record ids, national-dex order
 *   synthesized: string[],          // the record ids without their own initializer
 *   donorOf: Map<string, string>,   // synthesized id → the entry it copies
 *   entryFormTable: Map<string, string>,
 *   formTables: Map<string, string[]>,
 *   rosters: Map<string, string[]>, // record id → its form ids
 *   referenced: Set<string>,        // the union of every roster
 *   dexValue: Map<string, number>   // record id → national dex number
 * }
 */
export function formRosterDomain({ pokedexH, speciesTableTexts, formTableTexts, profiles, label = 'form-rosters' }) {
  const die = (msg) => { throw new Error(`${label}: ${msg}`); };

  // 1. the national dex enum (plain sequential; NONE = 0)
  const start = pokedexH.indexOf('NATIONAL_DEX_NONE');
  if (start < 0) die('NATIONAL_DEX_NONE not found in pokedex.h');
  const enumBlock = pokedexH.slice(start, pokedexH.indexOf('};', start));
  const records = [];
  const dexValue = new Map(); // record id -> national dex number
  let value = 0;
  for (const m of enumBlock.matchAll(/NATIONAL_DEX_([A-Z0-9_]+)/g)) {
    const id = m[1].toLowerCase();
    if (id === 'none') continue;
    records.push(id);
    dexValue.set(id, ++value);
  }
  if (records.length < 1000) die(`NATIONAL_DEX enum has ${records.length} members (expected ~1025)`);

  // 2. entries: macro-expanded .formSpeciesIdTable + .natDexNum per entry
  const entryIds = new Set();
  const entryFormTable = new Map(); // entry id -> form table name
  const entryDexValue = new Map();  // entry id -> national dex number
  for (const txt of speciesTableTexts) {
    const clean = stripComments(txt);
    const macros = collectMacros([clean]);
    for (const e of sliceEntries(clean)) {
      const id = e.id.toLowerCase();
      entryIds.add(id);
      const expanded = expandBody(e.body, macros);
      const ft = /\.formSpeciesIdTable\s*=\s*(s[A-Za-z0-9_]+FormSpeciesIdTable)/.exec(expanded);
      if (ft) entryFormTable.set(id, ft[1]);
      const nd = /\.natDexNum\s*=\s*NATIONAL_DEX_([A-Z0-9_]+)/.exec(expanded);
      if (nd) {
        const v = dexValue.get(nd[1].toLowerCase());
        if (typeof v === 'number') entryDexValue.set(id, v);
      }
    }
  }
  if (entryIds.size < 1500) die(`only ${entryIds.size} species entries parsed (expected ~1505)`);

  // 3. form tables (the same regex the pokedex extractor uses)
  const formTables = new Map(); // table name -> member ids (entry-backed only)
  const tableRe = /static const u16 (s[A-Za-z0-9_]+FormSpeciesIdTable)\[\]\s*=\s*\{([\s\S]*?)\};/g;
  for (const txt of formTableTexts) {
    let m;
    const re = new RegExp(tableRe.source, 'g');
    while ((m = re.exec(stripComments(txt)))) {
      const ids = [...m[2].matchAll(/SPECIES_([A-Z0-9_]+)/g)].map((s) => s[1].toLowerCase()).filter((s) => entryIds.has(s));
      if (ids.length > 0) formTables.set(m[1], ids);
    }
  }
  for (const t of new Set(entryFormTable.values())) {
    if (!formTables.has(t)) die(`entry form table ${t} not parsed from the form-table headers`);
  }

  // 4. synthesized bases (a record id with no initializer of its own):
  //    value group = the entries sharing the record's national dex number;
  //    the donor is the group member with an initializer
  const valueGroups = new Map(); // dex number -> entry ids
  for (const [id, v] of entryDexValue) {
    if (!valueGroups.has(v)) valueGroups.set(v, []);
    valueGroups.get(v).push(id);
  }
  const synthesized = [];
  const donorOf = new Map();
  for (const r of records) {
    if (entryIds.has(r)) continue;
    const donor = (valueGroups.get(dexValue.get(r)) ?? []).find((g) => entryIds.has(g));
    if (!donor) die(`${r}: national-dex species with no species initializer of its own or in any form`);
    synthesized.push(r);
    donorOf.set(r, donor);
  }

  // 5. per-record rosters
  const recordTable = new Map(); // record id -> its family form table
  for (const r of records) {
    const t = entryFormTable.get(r) ?? (donorOf.has(r) ? entryFormTable.get(donorOf.get(r)) : undefined);
    if (t) recordTable.set(r, t);
  }
  const tableBase = new Map(); // form table -> first record member (dex order)
  for (const [table, ids] of formTables) {
    const base = records.find((r) => ids.includes(r)) ?? ids[0];
    if (base) tableBase.set(table, base);
  }
  const rosters = new Map();
  const referenced = new Set();
  for (const r of records) {
    const pid = profiles.has(r) ? r : (tableBase.get(recordTable.get(r) ?? '') ?? r);
    const p = profiles.get(pid);
    let roster;
    if (p && p.length > 1) {
      roster = p.slice(1);
    } else {
      const t = recordTable.get(r);
      const ids = t ? formTables.get(t) : undefined;
      roster = ids && ids.length > 1 ? ids.filter((f) => f !== r) : [];
    }
    rosters.set(r, roster);
    for (const f of roster) referenced.add(f);
  }

  return { records, synthesized, donorOf, entryFormTable, formTables, rosters, referenced, dexValue };
}

/**
 * Merge the evo-driven roster additions (evolutions.mjs's `evoLinks` `refs`)
 * into a `formRosterDomain` result: the affected records' rosters gain the
 * extra form ids after the base roster (the same union the pokedex
 * extractor applies as evoRosterOf, so both extractors' form lists — and
 * hence the shipped <formEntryId>.png set — can never drift), and
 * `referenced` grows accordingly. Pure: the input domain is not mutated.
 *
 * @param {object} domain        a formRosterDomain() result (before merging)
 * @param {Map<string, string[]>} extraRosters  record id → extra form ids
 * @returns the merged domain (same shape as formRosterDomain() output)
 */
export function addExtraRosters(domain, extraRosters) {
  const rosters = new Map(domain.rosters);
  const referenced = new Set(domain.referenced);
  for (const [rec, extra] of extraRosters) {
    if (!domain.rosters.has(rec)) throw new Error(`addExtraRosters: unknown record ${rec}`);
    const base = rosters.get(rec);
    const merged = [...base, ...extra.filter((f) => !base.includes(f))];
    rosters.set(rec, merged);
    for (const f of merged) referenced.add(f);
  }
  return { ...domain, rosters, referenced };
}
